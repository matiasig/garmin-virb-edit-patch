function Write-Bytes([int]$offset, [byte[]]$patch) {
    [Array]::Copy($patch, 0, $bytes, $offset, $patch.Length)
}

function Patch-Pattern([string]$name, [byte[]]$orig, [byte[]]$patched) {
    if ($orig.Length -ne $patched.Length) {
        throw "Length mismatch for ${name}: $($orig.Length) vs $($patched.Length)"
    }
    $matches = [BinaryPatcher]::FindPattern($bytes, $orig)
    if ($matches.Count -ne 1) {
        throw "Expected 1 match for $name, found $($matches.Count)"
    }
    $offset = $matches[0]
    Write-Bytes $offset $patched
    Write-Host ("Patched {0} at offset {1} (0x{1:X})" -f $name, $offset)
}

